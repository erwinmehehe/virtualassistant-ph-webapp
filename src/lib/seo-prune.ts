function pathnameFromHref(href: string) {
  const pathname = href.split(/[?#]/, 1)[0];
  return pathname.startsWith("/") ? pathname.replace(/\/+$/, "") || "/" : "";
}

export function isPrunedRedirectSource(href: string) {
  return SEO_PRUNE_REDIRECT_PATHS.has(pathnameFromHref(href));
}

/** Repoint a site-owned internal URL to the final destination in one hop. */
export function resolvePrunedSeoHref(href: string) {
  const originalPath = href.split(/[?#]/, 1)[0];
  let current = pathnameFromHref(href);
  if (!current) return href;
  const visited = new Set<string>();
  while (SEO_PRUNE_REDIRECTS[current] && !visited.has(current)) {
    visited.add(current);
    current = SEO_PRUNE_REDIRECTS[current];
  }
  return visited.size ? current + href.slice(originalPath.length) : href;
}
